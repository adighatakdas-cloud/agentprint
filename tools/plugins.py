"""The plugin, extension and registry files for each AI agent ecosystem.

tools/gen_docs.py writes these and `--check` reports drift, so a version bump regenerates them.
Every value that comes from agentprint is computed here: the version (agentprint.__version__),
each hook entry (taken from the integration's own `edits()`, the entry `agentprint install`
writes, with the plugin's uvx command from agentprint/plugins.py), each MCP server entry, and
the instruction text (agentprint/integrations/base.py INSTRUCTIONS).

Shapes follow each ecosystem's docs as read on 2026-11-07; the research note behind them is
"agentprint plugin formats (2026-11)". Where a docs page did not show a file's format, the file
uses the closest documented shape and site/src/content/docs/plugins.md says "docs-verified only".
"""

from __future__ import annotations

import json
import tomllib
import urllib.parse
from pathlib import Path

import agentprint
from agentprint import plugins
from agentprint.guard import COULD_NOT_START, strict_block
from agentprint.integrations import ALL_INTEGRATIONS
from agentprint.integrations.base import BLOCK_EXIT, INSTRUCTIONS, FileEdit, JsonEdit, Launch
from agentprint.integrations.cursor import RULE as CURSOR_RULE

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES = Path(__file__).resolve().parent / "templates"
PLUGIN = ROOT / "plugins" / "agentprint"  # the Claude Code plugin; other ecosystems below it
VERSION = agentprint.__version__
NAME = plugins.NAME
MCP_NAME = "io.github.adighatakdas-cloud/agentprint"  # the official MCP registry's name
MCP_MARKER = f"<!-- mcp-name: {MCP_NAME} -->"  # in README.md, which is PyPI's page
OWNER = "adighatakdas-cloud"
REPO = f"https://github.com/{OWNER}/agentprint"
DESCRIPTION = (
    "Stops your AI coding agent from publishing a package or running git push that would leak "
    "API keys or agent files, and gives it an MCP server to check first. Offline."
)
SHORT = "Offline security check for AI coding agents: stops leaky package publishes and pushes"
GENERATED = "Generated by tools/gen_docs.py from agentprint's code; edit that, not this file."
# Never touched: edits() only compute text, and this folder is never created or read.
NOWHERE = Path("/nonexistent/agentprint-plugin-home")


def _project() -> dict:
    return tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]


def _author() -> dict:
    author = _project()["authors"][0]
    return {"name": author["name"], "email": author["email"]}


def _license() -> str:
    return _project()["license"]


class PluginLaunch(Launch):
    """A Launch whose hooks run the plugin command (uvx, pinned) instead of install's launcher."""

    def hook_command(self, agent: str, allow: str = "") -> str:
        return plugins.hook_command(agent, allow)


LAUNCH = PluginLaunch(hook="", mcp=plugins.mcp_argv())


def _json(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def install_text(agent: str, kind: str) -> str:
    """What `agentprint install` would write for `agent` (kind "hook" or "MCP"), as one file of
    its own, with the plugin's commands in it."""
    for edit in ALL_INTEGRATIONS[agent].edits(NOWHERE, {}, LAUNCH):
        if edit.what.startswith(kind) and isinstance(edit, JsonEdit | FileEdit):
            return edit.apply(None)
    raise LookupError(f"{agent} has no {kind} edit")


def install_json(agent: str, kind: str) -> dict:
    return json.loads(install_text(agent, kind))


def mcp_server(agent: str) -> dict:
    """The agentprint MCP server entry `install` writes for `agent`, with the plugin's command."""
    return install_json(agent, "MCP")["mcpServers"][NAME]


def plain_server() -> dict:
    command, *args = plugins.mcp_argv()
    return {"command": command, "args": args}


def skill(agent_word: str = "agent") -> str:
    description = (
        "Use before publishing a package (npm, pnpm, yarn or bun publish, uv publish, twine "
        "upload, poetry, hatch or flit publish) or running git push, and whenever agentprint "
        f"says BLOCK: how the {agent_word} checks with agentprint, fixes what it finds and tells "
        "the user what only they can do."
    )
    return (
        f"---\nname: {NAME}\ndescription: {json.dumps(description)}\n---\n\n"
        f"<!-- {GENERATED} -->\n\n{INSTRUCTIONS}"
    )


def _plugin_manifest(**extra: object) -> dict:
    return {
        "name": NAME,
        "version": VERSION,
        "description": DESCRIPTION,
        "author": _author(),
        "homepage": REPO,
        "repository": REPO,
        "license": _license(),
        **extra,
    }


def _marketplace(source: str) -> dict:
    """Claude Code's marketplace.json shape (Copilot CLI and Cursor document the same keys)."""
    return {
        "name": NAME,
        "owner": _author(),
        "plugins": [{"name": NAME, "source": source, "description": DESCRIPTION}],
    }


# ---- per ecosystem ------------------------------------------------------------------------------


def claude_code() -> dict[Path, str]:
    """https://code.claude.com/docs/en/plugins-reference ,
    https://code.claude.com/docs/en/plugin-marketplaces"""
    return {
        ROOT / ".claude-plugin" / "marketplace.json": _json(_marketplace("./plugins/agentprint")),
        PLUGIN / ".claude-plugin" / "plugin.json": _json(_plugin_manifest()),
        PLUGIN / "hooks" / "hooks.json": install_text("claude-code", "hook"),
        PLUGIN / ".mcp.json": _json({"mcpServers": {NAME: mcp_server("claude-code")}}),
        PLUGIN / "skills" / NAME / "SKILL.md": skill(),
    }


def codex() -> dict[Path, str]:
    """https://developers.openai.com/codex/plugins/build (Agent Plugins 1.0 manifest)."""
    folder = PLUGIN / "codex"
    marketplace = {
        "name": NAME,
        "interface": {"displayName": NAME},
        "plugins": [
            {
                "name": NAME,
                "source": {"source": "local", "path": "./plugins/agentprint/codex"},
                "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                "category": "Security",
            }
        ],
    }
    manifest = {
        "$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
        "name": NAME,
        "version": VERSION,
        "description": DESCRIPTION,
    }
    mcp = {
        "$schema": "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json",
        "mcpServers": {NAME: {"type": "stdio", **plain_server()}},
    }
    return {
        ROOT / ".agents" / "plugins" / "marketplace.json": _json(marketplace),
        folder / "plugin.json": _json(manifest),
        folder / "hooks" / "hooks.json": install_text("codex", "hook"),
        folder / "mcp.json": _json(mcp),
        folder / "skills" / NAME / "SKILL.md": skill(),
    }


def copilot() -> dict[Path, str]:
    """https://docs.github.com/en/copilot/reference/cli-plugin-reference"""
    folder = PLUGIN / "copilot"
    marketplace = _marketplace("./plugins/agentprint/copilot")
    return {
        ROOT / ".github" / "plugin" / "marketplace.json": _json(marketplace),
        folder / ".github" / "plugin" / "plugin.json": _json(_plugin_manifest()),
        folder / "hooks.json": install_text("copilot", "hook"),
        folder / ".mcp.json": _json({"mcpServers": {NAME: mcp_server("copilot")}}),
        folder / "skills" / NAME / "SKILL.md": skill(),
    }


def gemini() -> dict[Path, str]:
    """https://geminicli.com/docs/extensions/reference/ : the manifest and hooks/ must sit at
    the root of the repository (the extension's root)."""
    context = PLUGIN / "gemini" / "GEMINI.md"
    manifest = {
        "name": NAME,
        "version": VERSION,
        "description": DESCRIPTION,
        "contextFileName": context.relative_to(ROOT).as_posix(),
        "mcpServers": {NAME: mcp_server("gemini")},
    }
    return {
        ROOT / "gemini-extension.json": _json(manifest),
        ROOT / "hooks" / "hooks.json": install_text("gemini", "hook"),
        context: f"<!-- {GENERATED} -->\n\n{INSTRUCTIONS}",
    }


def cursor() -> dict[Path, str]:
    """https://cursor.com/docs/reference/plugins . Its plugin examples show hooks/hooks.json
    without the standalone file's `"version": 1` and mcp.json servers without `type` (Cursor
    infers the transport from `command`), so both are left out; the rest is install's entry."""
    folder = PLUGIN / "cursor"
    hooks = install_json("cursor", "hook")
    hooks.pop("version")
    server = {k: v for k, v in mcp_server("cursor").items() if k != "type"}
    rule = CURSOR_RULE.replace(
        "<!-- Written by `agentprint install`; `agentprint uninstall` deletes this file. -->",
        f"<!-- Part of the agentprint plugin. {GENERATED} -->",
    )
    return {
        ROOT / ".cursor-plugin" / "marketplace.json": _json(
            _marketplace("plugins/agentprint/cursor")
        ),
        folder / ".cursor-plugin" / "plugin.json": _json(_plugin_manifest()),
        folder / "hooks" / "hooks.json": _json(hooks),
        folder / "mcp.json": _json({"mcpServers": {NAME: server}}),
        folder / "rules" / "agentprint.mdc": rule,
    }


def antigravity() -> dict[Path, str]:
    """https://antigravity.google/docs/build-plugins/ : plugin.json, hooks.json (named hook
    groups, the shape install writes to ~/.gemini/config/hooks.json), mcp_config.json and
    rules/<name>.md with `trigger` frontmatter, all at the plugin root."""
    from agentprint.integrations.antigravity import RULE

    folder = PLUGIN / "antigravity"
    manifest = {
        "$schema": "https://antigravity.google/schemas/v1/plugin.json",
        "name": NAME,
        "displayName": NAME,
        "version": VERSION,
        "description": DESCRIPTION,
    }
    rule = RULE.replace(
        "<!-- Written by `agentprint install`; `agentprint uninstall` deletes this file. -->",
        f"<!-- Part of the agentprint plugin. {GENERATED} -->",
    )
    return {
        folder / "plugin.json": _json(manifest),
        folder / "hooks.json": install_text("antigravity", "hook"),
        folder / "mcp_config.json": _json({"mcpServers": {NAME: mcp_server("antigravity")}}),
        folder / "rules" / "agentprint.md": rule,
    }


def _py_string(text: str, width: int = 72) -> str:
    """`text` as a parenthesized Python string literal, in pieces cut after a space that keep
    lines short."""
    pieces, piece = [], ""
    for word in text.split(" "):
        if piece and len(piece) + len(word) > width:
            pieces.append(piece)
            piece = ""
        piece += word + " "
    pieces.append(piece[:-1])
    return "(\n    " + "\n    ".join(json.dumps(p) for p in pieces) + "\n)"


def hermes() -> dict[Path, str]:
    """https://hermes-agent.nousresearch.com/docs/user-guide/features/plugins and .../hooks"""
    folder = PLUGIN / "hermes"
    manifest = (
        f"# {GENERATED}\n"
        f"name: {NAME}\n"
        f'version: "{VERSION}"\n'
        f"description: {json.dumps(DESCRIPTION)}\n"
        "provides_hooks:\n"
        "  - pre_tool_call\n"
    )
    code = fill(
        "hermes-plugin.py.txt",
        generated=GENERATED,
        command=json.dumps(list(plugins.guard_argv("hermes"))),
        timeout="25",  # Hermes blocks a callback that runs past its 30 s default
        blocked=str(BLOCK_EXIT),
        no_uvx=json.dumps(plugins.NO_UVX),
        no_uvx_strict=json.dumps(plugins.NO_UVX_STRICT),
        strict_block=_py_string(strict_block(COULD_NOT_START).reason.strip()),
        uv_dirs=json.dumps([d.replace("$HOME/", "~/") for d in plugins.UV_DIRS]),
        name=NAME,
    )
    return {
        folder / "plugin.yaml": manifest,
        folder / "__init__.py": code,
        folder / "skills" / NAME / "SKILL.md": skill(),
    }


def mcp_registry() -> dict[Path, str]:
    """server.json for the official MCP registry (prepared, not published):
    https://modelcontextprotocol.io/registry/package-types . packageArguments are passed after
    the package, so a client runs `uvx agentprint==<version> mcp`."""
    server = {
        "$schema": "https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json",
        "name": MCP_NAME,
        "title": NAME,
        "description": SHORT,
        "version": VERSION,
        "repository": {"url": REPO, "source": "github"},
        "packages": [
            {
                "registryType": "pypi",
                "identifier": NAME,
                "version": VERSION,
                "runtimeHint": "uvx",
                "packageArguments": [{"type": "positional", "value": "mcp"}],
                "transport": {"type": "stdio"},
            }
        ],
    }
    return {ROOT / "server.json": _json(server)}


def fill(template: str, **values: str) -> str:
    """A template from tools/templates/ with each {{key}} replaced."""
    text = (TEMPLATES / template).read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    if "{{" in text:
        raise ValueError(f"{template} has a placeholder with no value")
    return text


def plugin_readme() -> dict[Path, str]:
    text = fill("plugins-readme.md", generated=GENERATED, version=VERSION, owner=OWNER, repo=REPO)
    return {PLUGIN / "README.md": text}


def files() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for part in (
        claude_code,
        codex,
        copilot,
        gemini,
        cursor,
        antigravity,
        hermes,
        mcp_registry,
        plugin_readme,
    ):
        out |= part()
    return out


# ---- the docs page's generated block ------------------------------------------------------------


def vscode_server() -> dict:
    return {"name": NAME, "type": "stdio", **plain_server()}


def vscode_link() -> str:
    """VS Code's install link: https://code.visualstudio.com/docs/agents/reference/mcp-configuration"""
    config = json.dumps(vscode_server(), separators=(",", ":"))
    return f"vscode:mcp/install?{urllib.parse.quote(config, safe='')}"


def page_block() -> str:
    """The install commands on site/src/content/docs/plugins.md (they carry the version)."""
    return fill(
        "plugins-page.md",
        version=VERSION,
        owner=OWNER,
        repo=REPO,
        name=NAME,
        mcp=" ".join(plugins.mcp_argv()),
        mcp_command=plugins.mcp_argv()[0],
        mcp_args=json.dumps(list(plugins.mcp_argv()[1:])),
        vscode=json.dumps(vscode_server(), separators=(",", ":")),
        vscode_link=vscode_link(),
    ).rstrip("\n")
