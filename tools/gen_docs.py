"""Draw the docs pages that mirror the code: check pages, the README table, landing terminals.

    uv run python -m tools.gen_docs            # write every file
    uv run python -m tools.gen_docs --check    # list stale files, exit 1 if any

Titles, severities and one-line fixes come from the check modules; the prose comes from
site/check-notes/. Terminal fragments are rendered by the real renderers into a fixed-size
console that ignores the environment, so the files are byte-identical on any machine.
"""

from __future__ import annotations

import argparse
import html
import io
import json
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from rich.console import Console

import agentprint
from agentprint.checks import SCAN_CHECKS
from agentprint.checks import ap006_package_leak as ap006
from agentprint.integrations import ALL_INTEGRATIONS
from agentprint.models import Finding, Severity
from agentprint.report import FailOn
from agentprint.roster import SHORT_NAMES, AgentState
from agentprint.ui.results import render
from agentprint.ui.theme import theme
from agentprint.ui.welcome import welcome_lines

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "site"
SNAPSHOTS = ROOT / "tests" / "data" / "snapshots"
DOCS_URL = "https://adighatakdas-cloud.github.io/agentprint/"
README_START = "<!-- checks:start -->"
README_END = "<!-- checks:end -->"
SECTIONS = ("What it finds", "Why it matters", "How to fix", "Limits")
GENERATED = (
    "<!-- Generated by tools/gen_docs.py from agentprint/checks and site/check-notes. "
    "Edit those, then run: uv run python -m tools.gen_docs -->"
)
# What cli.run_scan_command prints for a home + project sweep; time and roster size are fixed
# so the file never changes between runs (3 = the agents marked found in the welcome fragment).
SCAN_HEADER = "agentprint scan  ~ + . · roster 3 · 0.38s"


@dataclass(frozen=True)
class CheckDoc:
    id: str
    title: str
    severity: str
    fix: str
    summary: str
    runs_in: tuple[str, ...]
    body: str

    @property
    def slug(self) -> str:
        return self.id.lower()


def _note(path: Path) -> tuple[dict[str, str], str]:
    """Split a check note into its frontmatter (flat `key: value` lines) and its body."""
    _, front, body = path.read_text().split("---\n", 2)
    meta = {}
    for line in front.splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    return meta, body.strip() + "\n"


def check_docs() -> list[CheckDoc]:
    # (id, title, severity name or None, fix); AP006 is not a scan check, it has no severity
    rows = [(c.id, c.title, c.severity.name.lower(), c.fix) for c in SCAN_CHECKS]
    rows.append((ap006.ID, ap006.TITLE, "", ap006.FIX))
    docs = []
    for check_id, title, code_severity, fix in sorted(rows):
        meta, body = _note(SITE / "check-notes" / f"{check_id.lower()}.md")
        note = meta.get("severity_note", "")
        severity = f"{code_severity}; {note}" if code_severity and note else code_severity or note
        runs = meta["runs_in"].strip("[]").split(",")
        docs.append(
            CheckDoc(
                check_id,
                title,
                severity,
                fix,
                meta["summary"],
                tuple(r.strip() for r in runs),
                body,
            )
        )
    return docs


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def check_page(doc: CheckDoc) -> str:
    front = (
        "---\n"
        f"title: {json.dumps(f'{doc.id}: {doc.title}', ensure_ascii=False)}\n"
        f"description: {json.dumps(doc.summary, ensure_ascii=False)}\n"
        f"sidebar: {{ label: {json.dumps(f'{doc.id} {doc.title}', ensure_ascii=False)} }}\n"
        "---\n\n"
    )
    glance = (
        "| | |\n|---|---|\n"
        f"| Severity | {_cell(doc.severity)} |\n"
        f"| Runs in | {', '.join(doc.runs_in)} |\n"
        f"| One-line fix | {_cell(doc.fix)} |\n"
    )
    return f"{front}{GENERATED}\n\n{glance}\n{doc.body}"


def _table(docs: list[CheckDoc], link: str, summary_header: str) -> str:
    rows = [f"| ID | {summary_header} | Severity |", "|---|---|---|"]
    for d in docs:
        rows.append(f"| [{d.id}]({link}{d.slug}/) | {_cell(d.summary)} | {_cell(d.severity)} |")
    return "\n".join(rows)


def checks_index(docs: list[CheckDoc]) -> str:
    return (
        "---\ntitle: Checks\n"
        "description: What agentprint looks for, and how to fix each print.\n---\n\n"
        f"{GENERATED}\n\n"
        "Each check has an ID. Open one to see what it finds, why it matters and how to fix it.\n\n"
        f"{_table(docs, '/agentprint/checks/', 'What it finds')}\n\n"
        "Every print has a severity: critical, high, medium or low. `--fail-on` sets the lowest "
        "severity that counts (default `high`).\n"
        "The verdict is BLOCK when any print is at or above it, and CLEAR when none is.\n"
    )


def readme_checks_block(docs: list[CheckDoc]) -> str:
    return _table(docs, f"{DOCS_URL}checks/", "What it finds")


def replace_block(text: str, block: str) -> str:
    for marker in (README_START, README_END):
        if text.count(marker) != 1:
            raise ValueError(f"README.md needs exactly one {marker} line")
    head, rest = text.split(README_START)
    _, tail = rest.split(README_END)
    return f"{head}{README_START}\n{block}\n{README_END}{tail}"


def _recording_console() -> Console:
    return Console(
        file=io.StringIO(),
        record=True,
        width=80,
        force_terminal=True,
        color_system="truecolor",
        no_color=False,
        legacy_windows=False,
        theme=theme({}),
        _environ={},
    )


def _export(console: Console) -> str:
    return console.export_html(inline_styles=True, code_format="{code}")


def _welcome() -> str:
    found = {"claude-code": True, "codex": True, "cursor": False}
    states = [
        AgentState(n, label, n in found, found.get(n, False)) for n, label in SHORT_NAMES.items()
    ]
    console = _recording_console()
    for line in welcome_lines(states, agentprint.__version__, "~/code/my-app", width=80):
        console.print(line)
    return _export(console)


def _scan() -> str:
    data = json.loads((SNAPSHOTS / "scan.json").read_text())

    def place(text: str) -> str:
        return text.replace("<TMP>/home", "~").replace("<TMP>/proj", "~/code/my-app")

    findings = [
        Finding(
            f["check_id"],
            Severity[f["severity"].upper()],
            f["title"],
            f["agent"],
            place(f["location"]),
            f["line"],
            f["detail"],
            f["fix"],
            f["count"],
        )
        for f in data["findings"][:5]
    ]
    console = _recording_console()
    render(findings, console, fail_on=FailOn.high, header=SCAN_HEADER)
    return _export(console)


def _agent() -> str:
    text = (SNAPSHOTS / "pack.agent.txt").read_text()
    return f'<span style="color: #D5DEE8">{html.escape(text)}</span>'


def agent_names() -> list[str]:
    """The landing page's "Works inside" line: every integration, by its roster name, in roster
    order (an integration with no short name keeps its own label and goes last)."""
    order = list(SHORT_NAMES)
    names = sorted(ALL_INTEGRATIONS, key=lambda n: order.index(n) if n in order else len(order))
    return [SHORT_NAMES.get(n, ALL_INTEGRATIONS[n].label) for n in names]


def terminal_fragments() -> dict[str, str]:
    return {"welcome": _welcome(), "scan": _scan(), "agent": _agent()}


def outputs() -> dict[Path, str]:
    docs = check_docs()
    pages = SITE / "src" / "content" / "docs" / "checks"
    files = {pages / "index.md": checks_index(docs)}
    files |= {pages / f"{d.slug}.md": check_page(d) for d in docs}
    summaries = [
        {"id": d.id, "title": d.title, "severity": d.severity, "summary": d.summary, "slug": d.slug}
        for d in docs
    ]
    files[SITE / "src" / "data" / "checks.json"] = (
        json.dumps(summaries, indent=2, ensure_ascii=False) + "\n"
    )
    files[SITE / "src" / "data" / "agents.json"] = (
        json.dumps(agent_names(), indent=2, ensure_ascii=False) + "\n"
    )
    for name, fragment in terminal_fragments().items():
        files[SITE / "src" / "data" / "terminal" / f"{name}.html"] = fragment
    readme = ROOT / "README.md"
    files[readme] = replace_block(readme.read_text(), readme_checks_block(docs))
    return files


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="gen_docs", description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale files, write nothing")
    args = parser.parse_args(argv)
    stale = 0
    for path, text in outputs().items():
        if path.exists() and path.read_text() == text:
            continue
        if args.check:
            print(path)
            stale += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
