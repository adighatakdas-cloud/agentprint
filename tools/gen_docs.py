@dataclass(frozen=True)
class CheckDoc:
    id: str
    title: str
    severity: str
    fix: str
    summary: str
    runs_in: tuple[str, ...]
    body: str

    @property
    def slug(self) -> str:
        return self.id.lower()


def _note(path: Path) -> tuple[dict[str, str], str]:
    """Split a check note into its frontmatter (flat `key: value` lines) and its body."""
    _, front, body = path.read_text(encoding="utf-8").split("---\n", 2)
    meta = {}
    for line in front.splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip()
    return meta, body.strip() + "\n"


def check_docs() -> list[CheckDoc]:
    # (id, title, severity name or None, fix); AP006 is not a scan check, it has no severity
    rows = [(c.id, c.title, c.severity.name.lower(), c.fix) for c in SCAN_CHECKS]
    rows.append((ap006.ID, ap006.TITLE, "", ap006.FIX))
    rows.append((ap009.ID, ap009.TITLE, "", ap009.FIX))
    docs = []
    for check_id, title, code_severity, fix in sorted(rows):
        meta, body = _note(SITE / "check-notes" / f"{check_id.lower()}.md")
        note = meta.get("severity_note", "")
        severity = f"{code_severity}; {note}" if code_severity and note else code_severity or note
        runs = meta["runs_in"].strip("[]").split(",")
        docs.append(
            CheckDoc(
                check_id,
                title,
                severity,
                fix,
                meta["summary"],
                tuple(r.strip() for r in runs),
                body,
            )
        )
    return docs


def _cell(text: str) -> str:
    """Escape what Markdown would read as markup in a table cell: `|`, `<`, `*`, `_`, backtick."""
    return re.sub(r"([|<*_`])", r"\\\1", text)


def check_page(doc: CheckDoc) -> str:
    front = (
        "---\n"
        f"title: {json.dumps(f'{doc.id}: {doc.title}', ensure_ascii=False)}\n"
        f"description: {json.dumps(doc.summary, ensure_ascii=False)}\n"
        f"sidebar: {{ label: {json.dumps(f'{doc.id} {doc.title}', ensure_ascii=False)} }}\n"
        f"editUrl: {EDIT_BASE}/{doc.slug}.md\n"
        "---\n\n"
    )
    glance = (
        "| | |\n|---|---|\n"
        f"| Severity | {_cell(doc.severity)} |\n"
        f"| Runs in | {', '.join(doc.runs_in)} |\n"
        f"| One-line fix | {_cell(doc.fix)} |\n"
    )
    return f"{front}{GENERATED}\n\n{glance}\n{doc.body}"


BENCH_RESULTS = ROOT / "bench" / "results.json"
BENCH_TEMPLATE = ROOT / "bench" / "page.md"
BENCH_TOOLS = ("agentprint", "gitleaks", "trufflehog")


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.0f}%"


def _bench_name(category: str) -> str:
    kind, _, rest = category.partition("-")
    rest = rest.replace("-", " ")
    return {"plain": f"plain, in {rest}", "obf": f"hidden: {rest}"}.get(kind, rest)


def _key_group(categories: dict, prefix: str) -> str:
    """Recall over the plain- or obf- positive rows, as "95% (40 of 42)"."""
    group = key_recall(categories, prefix)
    return f"{_pct(group['recall'])} ({group['found']} of {group['cases']})"


def benchmark_page(results: dict) -> str:
    """The benchmark page: numbers come from bench/results.json, prose is fixed here."""
    tools = [t for t in BENCH_TOOLS if t in results["tools"]]
    corpus = results["corpus"]
    ran = ", ".join(f"{t} {results['tools'][t]['version']}" for t in tools)
    absent = results.get("not_run", [])
    note = (
        f"Not included in this run: {', '.join(absent)} (not installed where it ran). "
        "Their columns are left out rather than guessed."
        if absent
        else "All three tools were included in this run."
    )
    rows = [
        "| Tool | Version | Recall | Recall, plain keys | Recall, hidden keys | Precision"
        " | Keys found | False positives | Recall, any hit in file |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for t in tools:
        r = results["tools"][t]
        o = r["overall"]
        # From the categories, so a results file written before these columns renders too.
        plain, hidden = (_key_group(r["categories"], prefix) for prefix in ("plain-", "obf-"))
        rows.append(
            f"| {t} | {r['version']} | {_pct(o['recall'])} | {plain} | {hidden} "
            f"| {_pct(o['precision'])} | {o['tp']} of {o['tp'] + o['fn']} "
            f"| {o['fp']} of {o['fp'] + o['tn']} | {_pct(o['any_hit']['recall'])} |"
        )
    overall = "\n".join(rows)
    cats = {}
    for t in tools:
        for name, c in results["tools"][t]["categories"].items():
            cats.setdefault(name, c["kind"])

    def table(kind: str, label: str, key: str, fmt) -> str:
        lines = [
            f"| {label} | Cases | " + " | ".join(tools) + " |",
            "|---|---|" + "---|" * len(tools),
        ]
        for name in sorted(
            (n for n, k in cats.items() if k == kind), key=lambda n: (n.startswith("obf"), n)
        ):
            n = results["tools"][tools[0]]["categories"][name]["cases"]
            cells = [fmt(results["tools"][t]["categories"][name]) for t in tools]
            lines.append(f"| {_bench_name(name)} | {n} | " + " | ".join(cells) + " |")
        return "\n".join(lines)

    found = table("positive", "Key written as", "recall", lambda c: f"{c['found']} of {c['cases']}")
    clean = table("negative", "Look-alike", "fp", lambda c: f"{c['false_positives']} flagged")
    values = {
        "generated": results["generated"],
        "cases": str(corpus["cases"]),
        "positives": str(corpus["positives"]),
        "hidden_cases": str(key_recall(results["tools"][tools[0]]["categories"], "obf-")["cases"]),
        "negatives": str(corpus["negatives"]),
        "seed": str(results["seed"]),
        "ran": ran,
        "note": note,
        "overall": overall,
        "found": found,
        "clean": clean,
    }
    text = BENCH_TEMPLATE.read_text(encoding="utf-8")
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    return text


def _table(docs: list[CheckDoc], link: str, summary_header: str) -> str:
    rows = [f"| ID | {summary_header} | Severity |", "|---|---|---|"]
    for d in docs:
        rows.append(f"| [{d.id}]({link}{d.slug}/) | {_cell(d.summary)} | {_cell(d.severity)} |")
    return "\n".join(rows)


def checks_index(docs: list[CheckDoc]) -> str:
    return (
        "---\ntitle: Checks\n"
        "sidebar: { label: All checks }\n"
        "editUrl: false\n"
        "description: What agentprint looks for, and how to fix each print.\n---\n\n"
        f"{GENERATED}\n\n"
        "Each check has an ID. Open one to see what it finds, why it matters and how to fix it.\n\n"
        f"{_table(docs, '/agentprint/checks/', 'What it finds')}\n\n"
        "Every print has a severity: critical, high, medium or low. `--fail-on` sets the lowest "
        "severity that counts (default `high`).\n"
        "The verdict is BLOCK when any print is at or above it, and CLEAR when none is.\n"
    )


def readme_checks_block(docs: list[CheckDoc]) -> str:
    return _table(docs, f"{DOCS_URL}checks/", "What it finds")


def replace_block(text: str, block: str) -> str:
    for marker in (README_START, README_END):
        if text.count(marker) != 1:
            raise ValueError(f"README.md needs exactly one {marker} line")
    head, rest = text.split(README_START)
    _, tail = rest.split(README_END)
    return f"{head}{README_START}\n{block}\n{README_END}{tail}"


def _recording_console() -> Console:
    return Console(
        file=io.StringIO(),
        record=True,
        width=80,
        force_terminal=True,
        color_system="truecolor",
        no_color=False,
        legacy_windows=False,
        theme=theme({}),
        _environ={},
    )


def _export(console: Console) -> str:
    return console.export_html(inline_styles=True, code_format="{code}")


def _welcome() -> str:
    found = {"claude-code": True, "codex": True, "cursor": False}
    states = [
        AgentState(n, label, n in found, found.get(n, False)) for n, label in SHORT_NAMES.items()
    ]
    console = _recording_console()
    for line in welcome_lines(states, agentprint.__version__, "~/code/my-app", width=80):
        console.print(line)
    return _export(console)


def landing_world(root: Path) -> tuple[Path, Path]:
    """The demo world laid out as on the landing: the fake home at root/home and the npm
    project at ~/code/my-app inside it. Returns (home, project)."""
    spec = importlib.util.spec_from_file_location("build_demo", DEMO)
    assert spec is not None and spec.loader is not None
    demo = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(demo)
    home = root / "home"
    project = home / "code" / "my-app"
    demo.build_home(home)
    demo.build_project(project)
    return home, project


@contextlib.contextmanager
def _fixed_env(home: Path) -> Iterator[None]:
    """While the demo runs, the process sees only a fixed environment: HOME is the demo home,
    nothing moves an agent's folder (GEMINI_CLI_HOME would point the sweep at a real one), and
    git (AP007) reads no config and never climbs out of the demo folder into a real repo."""
    saved = os.environ.copy()
    os.environ.clear()
    os.environ.update(
        {
            "PATH": saved.get("PATH", os.defpath),
            "HOME": str(home),
            "USERPROFILE": str(home),  # what Path.home() reads on Windows
            "GIT_CEILING_DIRECTORIES": str(home.parent),
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_GLOBAL": os.devnull,
        }
    )
    try:
        yield
    finally:
        os.environ.clear()
        os.environ.update(saved)


def _sweep_and_fix() -> tuple[str, str]:
    """The landing's two middle blocks, from one run of the real engine on the demo world:
    `agentprint scan` (ends on BLOCK), then `agentprint fix` answered y (ends on CLEAR).

    The world sits in a private temporary folder (0700, so AP008 never sees it as readable),
    HOME points at its fake home, and both blocks are drawn while it does: paths show from ~
    exactly as the CLI prints them. The fix journal's timestamp is never shown."""
    consoles = {"scan": _recording_console(), "fix": _recording_console()}
    with tempfile.TemporaryDirectory(prefix="agentprint-landing-") as tmp:
        root = Path(tmp).resolve()
        with _fixed_env(root / "home"):
            home, project = landing_world(root)
            before = scan(home, project)
            render(before, consoles["scan"], fail_on=FailOn.high, header=SCAN_HEADER)

            plan = fixer.plan(before)
            out = consoles["fix"]
            fixview.render_plan(plan, out, header=FIX_HEADER)
            # cli.run_fix_command asks with typer.confirm(..., prompt_suffix=" "); the answer
            # is what a person types. Plain text: the landing types the answer.
            out.print(Text(f"Apply {fixes(len(rows(plan.changes, plan.findings)))}? [y/N] y"))
            outcome = fixer.apply(plan, home)
            fixview.render_outcome(outcome, scan(home, project), out, FailOn.high, plan=plan)
    swept, fixed = _export(consoles["scan"]), _export(consoles["fix"])
    for fragment in (swept, fixed):  # a path of this machine must never reach the repo
        if str(root) in fragment or tmp in fragment:
            raise RuntimeError("a temporary path leaked into a landing fragment")
    return swept, fixed


def _agent() -> str:
    text = (SNAPSHOTS / "pack.agent.txt").read_text(encoding="utf-8")
    return f'<span style="color: #D5DEE8">{html.escape(text)}</span>'


def agent_names() -> list[str]:
    """The landing page's "Works inside" line: every integration, by its roster name, in roster
    order (an integration with no short name keeps its own label and goes last)."""
    order = list(SHORT_NAMES)
    names = sorted(ALL_INTEGRATIONS, key=lambda n: order.index(n) if n in order else len(order))
    return [SHORT_NAMES.get(n, ALL_INTEGRATIONS[n].label) for n in names]


def terminal_fragments() -> dict[str, str]:
    """The landing terminal's blocks, in the order it plays them."""
    swept, fixed = _sweep_and_fix()
    return {"welcome": _welcome(), "scan": swept, "fix": fixed, "agent": _agent()}


def outputs() -> dict[Path, str]:
    docs = check_docs()
    pages = SITE / "src" / "content" / "docs" / "checks"
    files = {pages / "index.md": checks_index(docs)}
    files |= {pages / f"{d.slug}.md": check_page(d) for d in docs}
    summaries = [
        {"id": d.id, "title": d.title, "severity": d.severity, "summary": d.summary, "slug": d.slug}
        for d in docs
    ]
    files[SITE / "src" / "data" / "checks.json"] = (
        json.dumps(summaries, indent=2, ensure_ascii=False) + "\n"
    )
    files[SITE / "src" / "data" / "agents.json"] = (
        json.dumps(agent_names(), indent=2, ensure_ascii=False) + "\n"
    )
    for name, fragment in terminal_fragments().items():
        files[SITE / "src" / "data" / "terminal" / f"{name}.html"] = fragment
    files[pages.parent / "benchmark.md"] = benchmark_page(
        json.loads(BENCH_RESULTS.read_text(encoding="utf-8"))
    )
    readme = ROOT / "README.md"
    files[readme] = replace_block(readme.read_text(encoding="utf-8"), readme_checks_block(docs))
    return files


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="gen_docs", description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report stale files, write nothing")
    args = parser.parse_args(argv)
    stale = 0
    for path, text in outputs().items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        if args.check:
            print(path)
            stale += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
