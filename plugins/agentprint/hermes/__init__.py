"""agentprint for Hermes Agent: check a package publish or git push before the terminal tool
runs it. Generated by tools/gen_docs.py from agentprint's code; edit that, not this file.

Hermes blocks the tool when a pre_tool_call callback raises or runs past
plugins.hook_callback_timeout (30 s by default), so this callback never raises and gives up
after 25 s: anything that stops agentprint from running lets the command through, with one
line on stderr (uvx missing is said once per session). AGENTPRINT_STRICT=1 reaches agentprint,
and there the same failures block the command instead (strict mode fails closed).
https://hermes-agent.nousresearch.com/docs/user-guide/features/plugins
"""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

COMMAND = ["uvx", "--from", "agentprint==0.1.1", "agentprint", "guard", "--agent", "hermes"]
TIMEOUT = 25
BLOCKED = 3
NO_UVX = "agentprint: uvx not found, so this command was not checked (install uv to turn it on)"
UV_DIRS = ["~/.local/bin", "~/.cargo/bin"]  # where uv's installer puts uvx, if PATH lacks it
FAILED = "agentprint: hook check failed ({}); the command was allowed"
NO_UVX_STRICT = "agentprint: uvx not found, so this command was not checked; blocked (strict mode)"
FAILED_STRICT = "agentprint: hook check failed ({}); the command was blocked (strict mode)"
STRICT_BLOCK = "agentprint: BLOCK (strict mode)\nagentprint could not start, so it could not check this command.\nStrict mode is on (AGENTPRINT_STRICT=1 or --strict), so a command agentprint cannot check is blocked. Fix the cause and retry, or ask the human to turn strict mode off."
SKILL = Path(__file__).parent / "skills" / "agentprint" / "SKILL.md"
_said = set()


def _say(line):
    if line not in _said:
        _said.add(line)
        print(line, file=sys.stderr)


def _strict():
    return os.environ.get("AGENTPRINT_STRICT", "").strip().lower() in {"1", "true", "yes", "on"}


def _could_not(line, strict_line):
    """agentprint could not run: one line, and the tool runs; in strict mode it is blocked."""
    if _strict():
        print(strict_line, file=sys.stderr)
        return {"action": "block", "message": STRICT_BLOCK}
    _say(line)
    return None


def check(tool_name="", args=None, task_id="", **kwargs):
    """Hermes pre_tool_call: None lets the tool run; a block dict stops it."""
    try:
        if tool_name != "terminal":
            return None
        found = os.pathsep.join(os.path.expanduser(folder) for folder in UV_DIRS)
        uvx = shutil.which("uvx") or shutil.which("uvx", path=found)
        if uvx is None:
            return _could_not(NO_UVX, NO_UVX_STRICT)
        payload = {
            "hook_event_name": "pre_tool_call",
            "tool_name": tool_name,
            "tool_input": args if isinstance(args, dict) else {},
            "cwd": os.getcwd(),
        }
        done = subprocess.run(
            [uvx, *COMMAND[1:]],
            input=json.dumps(payload),
            capture_output=True,
            text=True,
            timeout=TIMEOUT,
            check=False,
        )
        if done.stderr.strip():
            print(done.stderr.strip(), file=sys.stderr)
        answer = json.loads(done.stdout) if done.stdout.strip() else {}
        blocked = isinstance(answer, dict) and answer.get("decision") == "block"
        if blocked or done.returncode == BLOCKED:  # BLOCKED: strict mode, reply failed
            reason = (answer.get("reason") if blocked else None) or done.stderr.strip()
            reason = str(reason or "agentprint: BLOCK")
            return {"action": "block", "message": reason}
        if done.returncode != 0:
            why = f"exit {done.returncode}"
            return _could_not(FAILED.format(why), FAILED_STRICT.format(why))
    except Exception as exc:  # noqa: BLE001 - Hermes would block the tool on an exception
        why = type(exc).__name__
        return _could_not(FAILED.format(why), FAILED_STRICT.format(why))
    return None


def register(ctx):
    ctx.register_hook("pre_tool_call", check)
    try:
        ctx.register_skill("agentprint", str(SKILL))
    except Exception as exc:  # noqa: BLE001 - the hook matters more than the skill
        _say(f"agentprint: skill not registered ({type(exc).__name__})")
